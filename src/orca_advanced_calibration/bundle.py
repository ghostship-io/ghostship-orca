"""Bundle the library + plugin into one self-contained OrcaSlicer plugin file.

OrcaSlicer's **Install local plugin** copies a single file (``.py`` or ``.whl``)
into its plugin directory. A single ``.py`` is the simplest artifact to install
and to audit, so this module emits one: PEP 723 metadata, then a bootstrap that
installs the library modules into memory and finally runs the plugin entry.

The library sources are embedded verbatim and executed into synthetic module
objects, so relative imports behave exactly as they do from a real package. No
filesystem writes happen at import time, which matters because plugin file
creation is audited and would otherwise prompt the user.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from .params import DEFAULT_PRESET, PRESETS

# Executed in dependency order; each may import the ones before it. ``cli`` is
# deliberately absent: the plugin does not need it, and omitting it keeps the
# installed file smaller and free of an unused argparse dependency.
MODULE_ORDER = (
    "params",
    "plate",
    "three_mf",
    "handoff",
    "__init__",
    "plugin",
)
PACKAGE = "orca_advanced_calibration"

# PEP 723 + Orca plugin identity. Must be the first thing in the file.
_HEADER = """# /// script
# requires-python = ">=3.12"
#
# [tool.orcaslicer.plugin]
# name = "{name}"
# description = "{description}"
# author = "{author}"
# version = "{version}"
# ///
"""

_BOOTSTRAP_TEMPLATE = '''"""Self-contained OrcaSlicer plugin bundle -- generated, do not edit.

Source: https://github.com/ghostship-io/ghostship-orca
Generated by: orca-calibrate bundle

Regenerate rather than editing: the embedded module sources below are copied
verbatim from the package at build time. Installing this file performs no
filesystem writes; the modules are materialised in memory so the host's file
audit does not prompt.
"""

import sys
import types

# Library sources, as (module_name, source) pairs, in dependency order.
_SOURCES = {sources}

_PACKAGE = {package}


def _install_package():
    # A real package object, so ``from . import x`` and ``from .m import y``
    # resolve through sys.modules exactly as they do from an installed copy.
    package = types.ModuleType(_PACKAGE)
    package.__path__ = []  # marks it as a package
    package.__package__ = _PACKAGE
    package.__file__ = f"<bundle:{{_PACKAGE}}/__init__.py>"
    sys.modules[_PACKAGE] = package

    for name, source in _SOURCES:
        if name == "__init__":
            target = package
        else:
            target = types.ModuleType(f"{{_PACKAGE}}.{{name}}")
            target.__package__ = _PACKAGE
            target.__file__ = f"<bundle:{{_PACKAGE}}/{{name}}.py>"
            sys.modules[target.__name__] = target
            setattr(package, name, target)
        exec(compile(source, target.__file__, "exec"), target.__dict__)

    return package


_install_package()

# Importing the plugin module runs its ``@orca.plugin`` registration.
import importlib as _importlib

_importlib.import_module(f"{{_PACKAGE}}.plugin")
'''


def _library_root() -> Path:
    return Path(__file__).resolve().parent


def read_sources() -> list[tuple[str, str]]:
    """Return ``(module_name, source)`` pairs in dependency order."""
    root = _library_root()
    sources: list[tuple[str, str]] = []
    for name in MODULE_ORDER:
        path = root / f"{name}.py"
        sources.append((name, path.read_text(encoding="utf-8")))
    return sources


def plugin_metadata() -> dict[str, str]:
    """Identity written into the bundle's PEP 723 header."""
    return {
        "name": "Advanced Flow Calibration",
        "description": (
            "Generate an Ellis-style flow-ratio calibration plate with per-object "
            "print_flow_ratio overrides and send it to the plate."
        ),
        "author": "caelx",
        "version": _read_version(),
    }


def _read_version() -> str:
    pyproject = _library_root().parent.parent / "pyproject.toml"
    try:
        text = pyproject.read_text(encoding="utf-8")
    except OSError:
        return "0.1.0"
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("version") and "=" in stripped:
            return stripped.split("=", 1)[1].strip().strip('"').strip("'")
    return "0.1.0"


def build_bundle() -> str:
    """Produce the complete single-file plugin source."""
    meta = plugin_metadata()
    header = _HEADER.format(**meta)

    # json.dumps gives a valid, escaped Python literal for the module table.
    sources_literal = json.dumps(read_sources(), indent=4)
    body = _BOOTSTRAP_TEMPLATE.format(sources=sources_literal, package=repr(PACKAGE))
    return header + "\n" + body


def write_bundle(path: str | os.PathLike[str]) -> str:
    """Write the bundle to ``path``; returns the path as a string."""
    data = build_bundle()
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(data, encoding="utf-8")
    return str(target)


def default_bundle_name() -> str:
    return f"orca-advanced-calibration-plugin-{plugin_metadata()['version']}.py"


def bundle_summary() -> dict:
    """A short description of what the bundle contains, for CLI output."""
    return {
        "package": PACKAGE,
        "modules": [name for name, _ in read_sources()],
        "presets": sorted(PRESETS),
        "default_preset": DEFAULT_PRESET,
        "metadata": plugin_metadata(),
    }
